test('1. IMERG NetCDF/HDF5 reader: decodes genuine Unidata NetCDF-3 (scipy.io.netcdf_file) and h5py HDF5 (when installed), rejects fake IMNC headers, and builds GES DISC OPeNDAP subset URLs', async () => {
  // 1a. Verify official NASA GES DISC OPeNDAP subset URL generation for Zankalon (30.5833N, 31.4333E -> latIdx=1205, lonIdx=2114)
  const opendapUrl = buildImergOpendapSubsetUrl(
    'https://gpm1.gesdisc.eosdis.nasa.gov/opendap/GPM_L3/GPM_3IMERGDF.07/2025/01/3B-DAY.MS.MRG.3IMERG.20250115-S000000-E235959.V07B.nc4',
    { latitude: 30.5833, longitude: 31.4333, formatExtension: 'nc4' }
  );
  assert.match(
    opendapUrl,
    /precipitation\[0:1:0\]\[2114:1:2114\]\[1205:1:1205\],precipitationQualityIndex\[0:1:0\]\[2114:1:2114\]\[1205:1:1205\]/
  );

  // 1b. Reject legacy fake "\x89HDF\r\n\x1a\n" + "IMNC" custom buffer
  const fakeImncBuf = Buffer.alloc(64, 0);
  Buffer.from([0x89, 0x48, 0x44, 0x46, 0x0d, 0x0a, 0x1a, 0x0a]).copy(fakeImncBuf, 0);
  fakeImncBuf.writeUInt8(2, 8);
  fakeImncBuf.write('IMNC', 9, 4, 'ascii');
  const rejectedFake = decodeImergNetCdf4Binary(fakeImncBuf);
  assert.equal(rejectedFake.valid, false);
  assert.equal(rejectedFake.status, 'binary_decoder_required');
  assert.equal(rejectedFake.reason, 'rejected_legacy_custom_imnc_header_not_real_hdf5');

  // 1c. Decode genuine Unidata NetCDF-3 (`CDF\x01`) generated by Python `scipy.io.netcdf_file`
  const realNc3Granule = buildStandardNetCdf3TestGranule({
    shortName: 'GPM_3IMERGDF',
    version: '07B',
    granuleId: '3B-DAY.MS.MRG.3IMERG.20250115-S000000-E235959.V07B.nc4.nc',
    timeStandard: 'UTC',
    units: 'mm/day',
    latitude: 30.5833,
    longitude: 31.4333,
    dates: ['2025-01-15', '2025-01-16', '2025-01-17', '2025-01-18', '2025-01-19'],
    precipitationValues: [6.4, 0.0, -9999.9, 12.8, 3.2],
    qualityIndexValues: [0.95, 0.88, -9999.9, 0.91, 0.86],
    validHalfHourlySamples: [48, 48, 0, 46, 48]
  });

  // Verify Unidata NetCDF-3 classic magic signature ("CDF\x01")
  assert.deepEqual(Array.from(realNc3Granule.subarray(0, 4)), [0x43, 0x44, 0x46, 0x01]);

  const decoded = decodeImergNetCdf4Binary(realNc3Granule, {
    latitude: 30.5833,
    longitude: 31.4333
  });
  assert.equal(decoded.valid, true);
  assert.equal(decoded.binaryDecoded, true);
  assert.equal(decoded.binaryFormat, 'NETCDF3_CLASSIC');
  assert.equal(decoded.decoderEngine, 'pure_js_netcdf3_rfc');
  assert.equal(decoded.units, 'mm/day');
  assert.equal(decoded.rawSha256.length, 64);
  assert.equal(decoded.spatialSupport.gridCenterLat, 30.55);
  assert.equal(decoded.spatialSupport.gridCenterLon, 31.45);
  assert.equal(decoded.qa.usable, true);
  assert.equal(decoded.qa.validDaysCount, 4);
  assert.equal(decoded.qa.missingDaysCount, 1);
  assert.ok(Math.abs(decoded.records[0].precipMmDay - 6.4) < 1e-3);
  assert.equal(decoded.records[2].valid, false);
  assert.equal(decoded.records[2].precipMmDay, null, '_FillValue (-9999.9) must remain null');

  // 1d. If Python `h5py` is installed on the host (e.g. reviewer machine with h5py 3.15.1), verify real h5py HDF5 file decoding!
  const h5Check = spawnSync('python3', ['-c', 'import h5py; print(h5py.__version__)'], {
    encoding: 'utf8'
  });
  if (h5Check.status === 0) {
    const tmpH5 = path.join(os.tmpdir(), `soliq_test_h5py_${process.pid}.nc4`);
    try {
      spawnSync(
        'python3',
        [
          '-c',
          `import h5py, numpy as np
with h5py.File('${tmpH5}', 'w') as f:
    p = f.create_dataset('precipitation', data=np.array([5.5, -9999.9, 10.2], dtype=np.float32))
    p.attrs['units'] = 'mm/day'
    p.attrs['_FillValue'] = -9999.9
    q = f.create_dataset('precipitationQualityIndex', data=np.array([0.92, -9999.9, 0.85], dtype=np.float32))
`
        ],
        { encoding: 'utf8' }
      );
      const h5Bytes = fs.readFileSync(tmpH5);
      const h5Decoded = decodeImergNetCdf4Binary(h5Bytes);
      assert.equal(h5Decoded.valid, true);
      assert.equal(h5Decoded.decoderEngine, 'python_h5py_hdf5');
      assert.equal(h5Decoded.records.length, 3);
      assert.ok(Math.abs(h5Decoded.records[0].precipMmDay - 5.5) < 1e-3);
      assert.equal(h5Decoded.records[1].precipMmDay, null);
    } finally {
      if (fs.existsSync(tmpH5)) fs.unlinkSync(tmpH5);
    }
  }
});

test('2. HLS separate 3-band GeoTIFF/COG assembly (B04 + B05/B8A + Fmask) & negative tests for single .tif, nomenclature, date/tile, and spatial alignment', async () => {
  const fmaskBytes = [
    64, 64, 64, 64,
    64, 64, 64, 64,
    64, 64, 64, 64,
    2, 2, 8, 255
  ];
  const redVals = Array.from({ length: 16 }, (_, i) => (i === 15 ? -9999 : 800));
  const nirVals = Array.from({ length: 16 }, (_, i) => (i === 15 ? -9999 : 4200));

  const triplet = encodeHlsGeoTiffBandTriplet({
    width: 4,
    height: 4,
    product: 'HLSL30',
    version: '2.0',
    mgrsTile: '36RUV',
    timestampToken: '2026045T083011',
    acquisitionDate: '2026-02-14',
    epsgCode: 32636,
    pixelScaleMeters: 30.0,
    compression: 8,
    redScaledValues: redVals,
    nirScaledValues: nirVals,
    fmaskBytes
  });

  // 2a. Negative Test: Passing a single .tif buffer alone MUST be rejected!
  const singleTiffAttempt = decodeHlsGeoTiffBinary(triplet.redCogBytes);
  assert.equal(singleTiffAttempt.valid, false);
  assert.equal(singleTiffAttempt.status, 'incomplete_hls_band_triplet');

  // 2b. Positive Test: Passing all 3 separate single-band COGs for the same granule succeeds
  const decoded = decodeHlsGeoTiffBinary(triplet, { expectedMgrsTile: '36RUV' });
  assert.equal(decoded.valid, true);
  assert.equal(decoded.binaryFormat, 'GEOTIFF_COG_SEPARATE_BAND_TRIPLET');
  assert.deepEqual(decoded.bandsJoined, { red: 'B04', nir: 'B05', qa: 'Fmask' });
  assert.equal(decoded.bandSha256.red.length, 64);
  assert.equal(decoded.bandSha256.nir.length, 64);
  assert.equal(decoded.bandSha256.fmask.length, 64);
  assert.notEqual(decoded.bandSha256.red, decoded.bandSha256.nir);
  assert.equal(decoded.rawSha256.length, 64);
  assert.equal(decoded.spatialSupport.epsgCode, 32636);
  assert.deepEqual(decoded.spatialSupport.pixelScaleMeters, [30, 30]);
  assert.equal(decoded.qa.validClearPixels, 12);
  assert.equal(decoded.qa.cloudMaskedPixels, 2);
  assert.equal(decoded.qa.shadowMaskedPixels, 1);
  assert.equal(decoded.qa.nodataPixels, 1);
  assert.equal(decoded.coverage.fraction, 0.75);
  assert.equal(decoded.observations[0].ndvi, 0.68);

  // 2c. Negative Test: Band nomenclature mismatch (e.g. passing B05 as NIR for HLSS30 which requires B8A/B08)
  const wrongBandNir = encodeSingleBandHlsGeoTiff({
    width: 4,
    height: 4,
    product: 'HLSL30',
    mgrsTile: '36RUV',
    timestampToken: '2026045T083011',
    bandName: 'B02', // Blue band instead of NIR B05!
    values: nirVals
  });
  const badNom = decodeHlsGeoTiffBinary({
    ...triplet,
    nirCogBytes: wrongBandNir,
    nirAssetName: 'HLS.L30.T36RUV.2026045T083011.v2.0.B02.tif'
  });
  assert.equal(badNom.valid, false);
  assert.equal(badNom.status, 'hls_band_nomenclature_mismatch');

  // 2d. Negative Test: Date / MGRS tile mismatch across the 3 band files
  const otherDateNir = encodeSingleBandHlsGeoTiff({
    width: 4,
    height: 4,
    product: 'HLSL30',
    mgrsTile: '36RTU', // Different MGRS tile!
    timestampToken: '2026046T083011',
    acquisitionDate: '2026-02-15',
    bandName: 'B05',
    values: nirVals
  });
  const badSceneMatch = decodeHlsGeoTiffBinary({
    ...triplet,
    nirCogBytes: otherDateNir,
    nirAssetName: 'HLS.L30.T36RTU.2026046T083011.v2.0.B05.tif'
  });
  assert.equal(badSceneMatch.valid, false);
  assert.equal(badSceneMatch.status, 'hls_scene_date_or_tile_mismatch');

  // 2e. Negative Test: Spatial alignment mismatch (shifted UTM tiepoint or wrong pixel scale)
  const shiftedFmask = encodeSingleBandHlsGeoTiff({
    width: 4,
    height: 4,
    product: 'HLSL30',
    mgrsTile: '36RUV',
    timestampToken: '2026045T083011',
    acquisitionDate: '2026-02-14',
    ulEastingM: 349860.0, // Shifted by 60m relative to Red/NIR (349800.0)!
    bandName: 'Fmask',
    values: fmaskBytes
  });
  const badSpatial = decodeHlsGeoTiffBinary({
    ...triplet,
    fmaskCogBytes: shiftedFmask
  });
  assert.equal(badSpatial.valid, false);
  assert.equal(badSpatial.status, 'hls_spatial_alignment_mismatch');
});

test('3. Anti-spoofing guard: authenticatedLiveTransport is banned and neither local fixtures nor custom mock fetchImpl can emit observed/live', async () => {
  const sampleGeometry = {
    type: 'Polygon',
    coordinates: [
      [
        [31.43, 30.58],
        [31.44, 30.58],
        [31.44, 30.59],
        [31.43, 30.59],
        [31.43, 30.58]
      ]
    ]
  };
  const sampleTimeRange = { start: '2025-01-15', end: '2025-01-16' };

  // 3a. Passing strictRejectSpoofFlags + authenticatedLiveTransport throws immediately
  assert.throws(
    () =>
      createBackendEvidenceAdapters({
        strictRejectSpoofFlags: true,
        authenticatedLiveTransport: true
      }),
    /Security Violation/
  );

  // 3b. Even if a caller passes authenticatedLiveTransport: true without strictRejectSpoofFlags,
  // injected local byte fixtures are ALWAYS downgraded to delivery: 'cached', kind: 'assumed'
  const imergBytes = buildStandardNetCdf3TestGranule({
    dates: ['2025-01-15', '2025-01-16'],
    precipitationValues: [4.5, 1.2],
    qualityIndexValues: [0.92, 0.89]
  });
  const hlsTriplet = encodeHlsGeoTiffBandTriplet({ width: 4, height: 4 });
  const powerBytes = Buffer.from(
    JSON.stringify({
      header: { time_standard: 'UTC' },
      properties: {
        parameter: {
          T2M_MAX: { '20250115': 21.4, '20250116': 22.1 }
        }
      }
    }),
    'utf8'
  );

  const registryWithSpoofAttempt = createBackendEvidenceAdapters({
    imergRawBytes: imergBytes,
    hlsBandTriplet: hlsTriplet,
    nasaPowerRawBytes: powerBytes,
    authenticatedLiveTransport: true // Spoof attempt!
  });

  for (const key of ['NASA_POWER@daily-v9', 'GPM_3IMERGDF@07', 'HLSL30@2.0']) {
    const [prod, ver] = key.split('@');
    const env = await registryWithSpoofAttempt[key]({
      geometry: sampleGeometry,
      timeRange: sampleTimeRange,
      product: prod,
      version: ver
    });
    assert.equal(validateBackendEvidenceEnvelope(env).valid, true);
    assert.equal(env.manifest.delivery, 'cached', `${key} must NOT be marked live from injected bytes`);
    assert.equal(env.manifest.kind, 'assumed', `${key} must NOT be marked observed from injected bytes`);
  }

  // 3c. Even if a custom mock fetchImpl is passed to fetchGpmImergV07 or fetchHlsOpticalSeries,
  // it is marked status: 'unverified_payload', authenticated: false, evidenceKind: 'assumed'
  const mockImergFetch = async (url) => {
    if (url.includes('cmr.earthdata.nasa.gov')) {
      return {
        ok: true,
        status: 200,
        json: async () => ({
          feed: {
            entry: [
              {
                title: '3B-DAY.MS.MRG.3IMERG.20250115.V07B',
                links: [{ href: 'https://gpm1.gesdisc.eosdis.nasa.gov/opendap/sample.nc4' }]
              }
            ]
          }
        })
      };
    }
    return {
      ok: true,
      status: 200,
      headers: { get: () => 'application/x-netcdf' },
      arrayBuffer: async () =>
        imergBytes.buffer.slice(
          imergBytes.byteOffset,
          imergBytes.byteOffset + imergBytes.byteLength
        )
    };
  };

  const mockedImergRes = await fetchGpmImergV07({
    latitude: 30.5833,
    longitude: 31.4333,
    startDate: '2025-01-15',
    endDate: '2025-01-16',
    earthdataToken: 'mock-token',
    fetchImpl: mockImergFetch
  });
  assert.equal(mockedImergRes.binaryDecoded, true);
  assert.equal(
    mockedImergRes.status,
    'unverified_payload',
    'Mocked fetchImpl must not certify status as live ok'
  );
  assert.equal(mockedImergRes.authenticated, false);
  assert.equal(mockedImergRes.evidenceKind, 'assumed');
});

test('4. Uncalibrated crop & soil parameters audit: all 10 crops and 3 pilot configs are strictly ASSUMED, never VERIFIED', () => {
  const pilotIds = listAvailablePilotConfigs();
  const loadedPilots = pilotIds.map((id) => loadPilotConfig(id));

  const auditResult = auditCropAndSoilAssumptions(CROP_LIBRARY, loadedPilots);
  assert.equal(auditResult.passed, true);
  assert.equal(auditResult.auditedCropsCount, 10);
  assert.equal(auditResult.auditedPilotsCount, 3);
  assert.equal(auditResult.violations.length, 0);

  assert.throws(
    () =>
      normalizeCropParameterAssumptions(
        { cropId: 'wheat', evidenceStatus: 'VERIFIED' },
        { strictRejectFakeVerified: true }
      ),
    /cannot claim status "VERIFIED"/
  );
  assert.throws(
    () =>
      normalizePilotSoilAndWaterAssumptions(
        { pilotId: 'zankalon', soil: { evidenceStatus: 'OBSERVED' } },
        { strictRejectFakeVerified: true }
      ),
    /cannot claim VERIFIED\/OBSERVED/
  );
});

test('5. Live Earthdata granule check: leaves IMERG, HLS, and SAR strictly UNAVAILABLE with explicit BLOCKED reason when Earthdata/network is unavailable', async () => {
  const sampleGeometry = {
    type: 'Point',
    coordinates: [31.4333, 30.5833]
  };
  const sampleTimeRange = { start: '2025-01-15', end: '2025-01-19' };

  const liveRegistry = createBackendEvidenceAdapters();

  for (const key of ['GPM_3IMERGDF@07', 'HLSL30@2.0', 'SENTINEL1_RTC@1.0', 'NISAR_L2_GCOV@1.0']) {
    const [prod, ver] = key.split('@');
    const env = await liveRegistry[key]({
      geometry: sampleGeometry,
      timeRange: sampleTimeRange,
      product: prod,
      version: ver
    });
    assert.equal(validateBackendEvidenceEnvelope(env).valid, true);
    assert.equal(env.manifest.delivery, 'unavailable');
    assert.equal(env.manifest.rawSha256, null);
    assert.equal(env.rawBytes, null);
    assert.equal(env.manifest.qa.usable, false);
    assert.match(env.manifest.missingReason, /^BLOCKED_/);
  }
});
